def get_prompts(split: str) -> list[dict[str, str]]:
    bank = DEV_PROMPTS if split == "dev" else FINAL_PROMPTS
    return [
        {"id": f"{split}-{category}-{index:02d}", "category": category, "prompt": prompt}
        for category, prompts in bank.items()
        for index, prompt in enumerate(prompts, start=1)
    ]
